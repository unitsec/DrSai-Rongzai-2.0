const atomic_data* AtomicData(const string& symbol)
{
	Int4 atomNumber = 0;
	if(ZRTErrorTypeNotFoundAtomSymbolData == IntAtomicSymbol(symbol, atomNumber) ){
		return NULL;
	}
	return &AtomicData(atomNumber);
}

const atomic_data& AtomicData(const Int4& j)
{
	if(j<0 || j>=NUMDATA) throw ZRTErrorTypeNotFoundAtomSymbolData;
	return adata[j];
}

ZRTErrorType IntAtomicSymbol(const string& aname, Int4& ans)
{
	Int4 start = 0;
	while( start < (Int4)aname.length() && !isalpha( aname.at(start) ) ) start++;
	if( start < (Int4)aname.length() )
	{
		// si, SI -> Si
		string aname0 = aname;
		aname0.at(start) = toupper( aname.at(start) );
		for(UInt4 i=start+1; i<aname.length(); i++) aname0.at(i) = tolower( aname.at(i) );

		for(Int4 j=0; j<NUMDATA; j++)
		{
			if(adata[j].ZSymbolA==aname0)
			{
				ans = j;
				return ZRTErrorTypeNoError;
			}
		}
	}
    
	return ZRTErrorTypeNotFoundAtomSymbolData;
}



string ConvAtomicSymbol(const string atom_name)
{
	string name;
	if(atom_name.size() == 3) {
		if( atom_name == "Siv") {
			name = "Si";
		}
		else {
			string s(atom_name,0,1);
			name = s;
		}
	}
	else if(atom_name.size() == 4 ) {
		if(atom_name == "Cval") name = "C";
		else {
			string s(atom_name,0,2);
			name = s;
		}
	}
	else if(atom_name.size() == 5 ) {
		if(atom_name == "Sival") name = "Si";
		else  name = atom_name;
	}
	else {
		name = atom_name;
	}

	return name;
}

